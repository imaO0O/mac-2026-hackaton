# -*- coding: utf-8 -*-
"""Порог свежести серы СЫРЬЯ: почему он свой и почему он ничего не перекрывает.

Два разных утверждения, и оба проверяются здесь:

1. Порог обязан быть отдельным от порога продукта. Продукт анализируют раз в
   сутки, сырьё — по своему расписанию, и кратность «×7 от продукта» была
   назначена, а не измерена: она зажигала флаг больше чем в половине срезов.
2. Флаг не должен становиться воротами для кинетического суррогата. Это не
   недосмотр, а измеренное решение: сырьё входит в ответ только через
   ``tau = ln(S_вход / S_выход)``, где отношение около 1200, поэтому ошибка
   устаревшего значения стоит около процента приращения. Разбор —
   docs/QUALITY_AGENT.md.
"""
from __future__ import annotations

import math

import pytest

from nefte.config import load_config
from nefte.models.kinetics import DEFAULT_FEED_SULFUR_MGKG, arrhenius_factor


def test_feed_threshold_is_its_own_not_a_multiple_of_the_product_one():
    """У сырья свой порог, и он заметно больше суточного порога продукта."""
    stale = load_config()["quality"]["staleness_hours"]
    assert "lims_feed" in stale, (
        "порог свежести серы сырья должен быть задан явно: кратность порогу "
        "продукта — назначенное число, а расписания у них разные")
    assert stale["lims_feed"] > stale["lims"], (
        "сырьё анализируют реже продукта, порог не может быть строже")


def test_stale_feed_costs_about_one_percent_of_the_move():
    """Цена устаревшего значения сырья — проценты приращения, а не разы.

    Это и есть причина, по которой суррогат не смотрит на ``is_stale``:
    логарифм большого отношения почти не чувствует ошибку в числителе.
    """
    s_in, level = 9460.0, 8.0            # медиана сырья и типичный уровень продукта
    factor = arrhenius_factor(340.0, 342.0)

    def predict(feed: float) -> float:
        tau = math.log(feed / level)
        return feed * math.exp(-tau * (1.0 + (factor - 1.0)))

    base = predict(s_in) - level
    # 0.090 — медиана |ln S_тогда / S_сейчас| для значений старше месяца
    worst = predict(s_in * math.exp(0.090)) - level
    assert abs(worst - base) / abs(base) < 0.05, (
        "если устаревшее сырьё сдвигает приращение больше чем на 5 %, "
        "суррогат обязан смотреть на возраст — пересмотрите решение")


def test_default_feed_is_no_better_than_a_month_old_measurement():
    """Заглушка не спасение: она врёт не меньше, чем реальное старое значение.

    Отсюда следует, что подменять устаревшее измерение константой бессмысленно —
    это замена одной ошибки на такую же.
    """
    median_feed = 9534.0                 # медиана по обучающему периоду
    default_error = abs(math.log(DEFAULT_FEED_SULFUR_MGKG / median_feed))
    month_old_error = 0.090
    assert default_error >= month_old_error * 0.5, (
        "если заглушка стала заметно точнее старого измерения, "
        "выбор «старое измерение лучше константы» надо пересчитать")
