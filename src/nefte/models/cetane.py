"""Цетановое число: ограничение, тренд и цена его выполнения.

Организаторы назвали три обязательных показателя качества товарного дизеля:
**сера, Т95 и цетановое число**. Первые два у нас были, третьего не было вовсе —
и это оказалось не мелочью.

Что показывают выданные данные
------------------------------
Цетановое число меряется в ЛИМС примерно раз в месяц: 42 анализа за три с
половиной года, точка отбора «Гидроочистка, 2». И оно ПАДАЕТ год от года::

    2023  55.9 (14 анализов)
    2024  54.5 (11)
    2025  53.2 (11)
    2026  52.3 (6), последний анализ 21.07.2026 — 50.0

Норматив ЕН 590 — не ниже 51. Последний выданный анализ ниже норматива. То есть
показатель, который система обязана контролировать, уже вышел за предел, а мы о
нём не знали, потому что смотрели только на серу.

Почему не строим прогноз цетанового числа
-----------------------------------------
Классический цетановый ИНДЕКС (ASTM D976 по плотности и Т50) на этих данных не
работает: корреляция с лабораторией 0.03, разброс индекса 0.76 против 1.77 у
лаборатории. Индекс хуже, чем просто среднее по истории — и мы его не используем.
Проверка воспроизводится: ``python scripts/check_cetane.py``.

Сорок два анализа за три года — это не обучающая выборка. Поэтому цетановое число
входит в систему не как прогноз, а как **ограничение по последнему анализу с
поправкой на тренд**, и у ограничения есть цена: цетаноповышающая присадка.

Присадка
--------
Организаторы дали две цифры: дозировка до 3 % и цена в 100 раз выше дизеля за
тонну. Отклик на дозу в пакете не задан — взята насыщающаяся кривая, типичная для
2-этилгексилнитрата, и она объявлена ДОПУЩЕНИЕМ здесь и в docs/BLENDING.md.
Числа выбраны так, чтобы 0.1 % массы давали около +4 единиц: это середина
диапазона, который дают паспорта промышленных присадок.

Главный вывод про экономику виден сразу и без модели: при цене 100× даже 0.1 %
присадки стоит 10 % цены самого топлива. Присадка — дорогое лекарство, и система
обязана назначать минимальную дозу, закрывающую норматив, а не «с запасом».
"""
from __future__ import annotations

import math

import numpy as np
import pandas as pd

__all__ = [
    "CETANE_SPEC_MIN", "IMPROVER_MAX_PCT", "IMPROVER_PRICE_RATIO",
    "IMPROVER_PLATEAU", "IMPROVER_HALF_PCT",
    "cetane_index_d976", "improver_effect", "dose_for_deficit",
    "improver_cost_share", "trend_per_year",
]

# Норматив. ЕН 590 / ГОСТ 32511 — спецификация в пакете не выдана, это ДОПУЩЕНИЕ
# того же рода, что и остальные пределы в configs/config.yaml → spec.
CETANE_SPEC_MIN = 51.0

# Предел дозировки и цена — ОТВЕТ ОРГАНИЗАТОРОВ, не допущение.
IMPROVER_MAX_PCT = 3.0            # % массы
IMPROVER_PRICE_RATIO = 100.0      # цена присадки к цене дизеля, за тонну

# Отклик на дозу: ДОПУЩЕНИЕ. Насыщение — не украшение: без него модель обещала бы
# линейный рост цетанового числа до +300 единиц при 3 %, и оптимизатор радостно
# лечил бы присадкой любую проблему.
IMPROVER_PLATEAU = 10.0           # предельная прибавка, единиц ЦЧ
IMPROVER_HALF_PCT = 0.2           # доза, дающая 63 % плато, % массы


def cetane_index_d976(density_15c: float | None, t50_c: float | None) -> float | None:
    """Цетановый индекс ASTM D976 по плотности при 15 °C (кг/м3) и Т50 (°C).

    Оставлен для сопоставления и для отчёта: на выданных данных он с лабораторией
    не связан (см. модуль-докстринг), поэтому в решениях НЕ используется. Возвращает
    None на нефизичных входах — Т50 = 0 в ЛИМС встречается и в логарифм идти не должен.
    """
    if density_15c is None or t50_c is None:
        return None
    if not 700.0 < float(density_15c) < 950.0 or not 150.0 < float(t50_c) < 400.0:
        return None
    d = float(density_15c) / 1000.0
    b = float(t50_c)
    return float(454.74 - 1641.416 * d + 774.74 * d * d
                 - 0.554 * b + 97.803 * math.log10(b) ** 2)


def improver_effect(dose_pct: float) -> float:
    """Прибавка цетанового числа от присадки при дозировке ``dose_pct`` % массы.

    Насыщающаяся кривая ``A·(1 - exp(-x/x0))``. ДОПУЩЕНИЕ: паспорта присадки в
    пакете нет. Доза выше ``IMPROVER_MAX_PCT`` не даёт ничего сверх предела —
    ограничение организаторов, а не наше.
    """
    dose = max(0.0, min(float(dose_pct), IMPROVER_MAX_PCT))
    return IMPROVER_PLATEAU * (1.0 - math.exp(-dose / IMPROVER_HALF_PCT))


def dose_for_deficit(deficit: float) -> float | None:
    """Минимальная доза, закрывающая нехватку ``deficit`` единиц ЦЧ.

    Возвращает None, если нехватку не закрыть даже предельной дозой: тогда честный
    ответ — «этой смесью норматив не выполняется», а не доза, которой не хватит.
    """
    if deficit <= 0:
        return 0.0
    if deficit >= IMPROVER_PLATEAU:
        return None
    dose = -IMPROVER_HALF_PCT * math.log(1.0 - deficit / IMPROVER_PLATEAU)
    if dose > IMPROVER_MAX_PCT:
        return None
    return float(dose)


def improver_cost_share(dose_pct: float) -> float:
    """Стоимость присадки в долях цены тонны дизеля.

    При цене 100× и дозе 0.1 % массы получается 0.1 — десятая часть стоимости
    самого топлива. Это и есть ответ на вопрос «почему не лить присадку всегда».
    """
    return float(max(0.0, dose_pct) / 100.0 * IMPROVER_PRICE_RATIO)


def trend_per_year(series: pd.Series) -> float:
    """Наклон линейного тренда, единиц в год. Нужен, чтобы увидеть деградацию.

    Между анализами месяц, поэтому «последнее значение» стареет: если показатель
    падает на единицу в год, за месяц ожидание уходит на 0.08 — мало, а за
    полгода между редкими анализами уже на 0.5.
    """
    clean = series.dropna()
    if len(clean) < 3:
        return float("nan")
    years = (clean.index - clean.index[0]).total_seconds() / (365.25 * 24 * 3600)
    slope, _ = np.polyfit(np.asarray(years, dtype="float64"),
                          clean.to_numpy(dtype="float64"), 1)
    return float(slope)
