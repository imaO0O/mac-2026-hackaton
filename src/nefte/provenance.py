# -*- coding: utf-8 -*-
"""Откуда взялся отчёт: версия матрицы признаков и границы разбиения.

Отдельный модуль, а не блок в каждом скрипте, по той же причине, по которой в
проекте сведены счёт возраста лабораторных рядов и σ Т95: правило, написанное по
месту N раз, разъезжается на N-м. Здесь это уже случилось дважды.

* Девять отчётов нейросетей не записывали версию матрицы, а проверка свежести при
  отсутствии поля делает ``skip``. Пропуск в выводе pytest неотличим от успеха,
  поэтому контракт, который в своём же докстринге объявлял эти отчёты покрытыми,
  не проверял из них ни одного.
* Отчёты имитации и прогона по тестовому периоду оказались в том же положении, и
  обнаружилось это только когда числа из них попали в README.

Модуль намеренно ничего не знает про конкретный отчёт: он отвечает на один
вопрос — «на какой сборке это посчитано» — и отвечает одинаково для всех.
"""
from __future__ import annotations

from nefte.config import load_config


def report_provenance(cfg: dict | None = None) -> dict:
    """Поля происхождения для любого отчёта, зависящего от матрицы признаков.

    Кладётся в отчёт как есть::

        report = {**report_provenance(cfg), "своё": ...}

    ``split`` нужен наравне с версией: границы train/val/test — часть постановки,
    а не деталь прогона. Сдвинули разбиение — прежние метрики относятся к другому
    эксперименту, даже если матрица та же.
    """
    from nefte.models.dataset import FEATURE_VERSION

    cfg = cfg or load_config()
    return {
        "feature_version": FEATURE_VERSION,
        "split": {k: list(v) for k, v in cfg["split"].items()
                  if isinstance(v, (list, tuple))},
    }


def reliability_provenance(cfg: dict | None = None) -> dict:
    """Чем агент надёжности мерил тяжесть режима — для отчётов, где решал оркестратор.

    Отдельно от ``report_provenance``, потому что зависит от этого не всякий отчёт,
    а только тот, где работала тяжесть режима: прогоны системы, имитация, злые
    кейсы, бэктест надёжности. Обучению моделей качества поле не нужно, и если бы
    оно было в каждом отчёте, переключение выключателя «устаревало» бы и их.
    """
    cfg = cfg or load_config()
    settings = cfg.get("reliability") or {}
    return {"reliability_settings": {
        "catalyst_factor": settings.get("catalyst_factor", "age"),
        "catalyst_reset": settings.get("catalyst_reset", "outage_48h"),
        # входит ли перепад Р-202 в тяжесть режима: от этого зависят классы и,
        # через них, право оптимизатора поднимать температуру (docs/DP_PROXY.md)
        "dp_factor": settings.get("dp_factor", "off"),
    }}
